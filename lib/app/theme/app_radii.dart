/// Central corner-radius tokens for the pill / capsule design language.
class AppRadii {
  AppRadii._();

  static const double rounded = 999; // for elements that should always be fully rounded, regardless of size
  static const double card = 16; // cards, sheets, large containers
  static const double pill = 28; // pill rows, text fields, primary button
  static const double field = 24; // compact number inputs
  static const double tabContainer = 30; // segmented control container
  static const double tabSegment = 26; // active segment inside the container
  static const double dropdownMenu = 20; // dropdown popup list
  static const double rating = 8; // rating bar segments
}
